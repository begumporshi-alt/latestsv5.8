#!/usr/bin/env bash
#
# 03_restore.sh - restore the cutover dump into a NEW, EMPTY Supabase project.
#
# The restore runs in four ordered steps. The order is the whole point:
#
#   1. pre-data   tables and functions only (79 tables, ~186 functions)
#   2. auth       auth.users + auth.identities with original UUIDs
#   3. data       every row, with NO triggers in existence yet
#   4. post-data  indexes, constraints, RLS policies, triggers
#
# Step 3 must precede step 4. PostgreSQL's archive format places all user
# triggers in the post-data section, so restoring data before post-data means
# trg_invoice_accounting and trg_payment_accounting do not exist while rows
# load. If they did, each of the 1,299 restored invoices would post a second
# journal entry on top of the 6,680 already in the dump.
#
# The usual alternative, --disable-triggers or session_replication_role=replica,
# is unavailable: the `postgres` role on Supabase is not a superuser.
#
# Usage:
#   ./03_restore.sh --url <target-db-url> --dump <file.dump> [--force] [--dry-run]
#
set -euo pipefail

PGBIN="${PGBIN:-/opt/homebrew/opt/postgresql@17/bin}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOGDIR="$HERE/logs"

URL=""
DUMP=""
FORCE=0
DRY=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --url) URL="$2"; shift 2 ;;
    --dump) DUMP="$2"; shift 2 ;;
    --force) FORCE=1; shift ;;
    --dry-run) DRY=1; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

[[ -z "$URL" || -z "$DUMP" ]] && { echo "usage: $0 --url <url> --dump <file> [--force] [--dry-run]" >&2; exit 2; }
[[ -f "$DUMP" ]] || { echo "ERROR: dump not found: $DUMP" >&2; exit 2; }
mkdir -p "$LOGDIR"

PSQL="$PGBIN/psql"
PGRESTORE="$PGBIN/pg_restore"
TS="$(date +%Y%m%d-%H%M%S)"

say() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }

# ---------------------------------------------------------------- preflight
say "Preflight"

if ! "$PSQL" "$URL" -tAc "select 1" >/dev/null 2>&1; then
  echo "ERROR: cannot connect to target" >&2
  exit 1
fi

EXISTING=$("$PSQL" "$URL" -tAc \
  "select count(*) from pg_tables where schemaname='public' and tablename <> 'spatial_ref_sys'")

echo "target public tables: $EXISTING"
if [[ "$EXISTING" -gt 5 && "$FORCE" -eq 0 ]]; then
  cat >&2 <<EOF
ERROR: the target already has $EXISTING public tables.

This script is designed to populate an EMPTY project. Restoring over existing
data will produce duplicate-key errors and a half-built database.

If you are certain this is the right target, re-run with --force.
EOF
  exit 1
fi

for ext in pgcrypto uuid-ossp; do
  if [[ "$("$PSQL" "$URL" -tAc "select count(*) from pg_extension where extname='$ext'")" == "0" ]]; then
    echo "WARNING: extension '$ext' is not installed. Enable it in Dashboard -> Database -> Extensions." >&2
  fi
done

if [[ "$DRY" -eq 1 ]]; then
  cat <<EOF

Dry run. The following would execute:

  1. pg_restore -n public --section=pre-data
  2. psql -f auth_data.sql            (generated by 02_extract_auth.py)
  3. pg_restore -n public --section=data
  4. pg_restore -n public --section=post-data
  5. psql -f 04_post_restore.sql

No changes made.
EOF
  exit 0
fi

# ------------------------------------------------------------------- pass 1
say "Pass 1/4 - pre-data (tables, functions)"
LOG1="$LOGDIR/pre-data-$TS.log"
set +e
"$PGRESTORE" --no-owner --no-privileges -n public --section=pre-data \
  -d "$URL" "$DUMP" 2>"$LOG1"
RC1=$?
set -e
E1=$(grep -c '^pg_restore: error' "$LOG1" 2>/dev/null || true)
echo "exit=$RC1 errors=$E1  (log: $LOG1)"
if [[ "$E1" -gt 0 ]]; then
  echo "--- first errors ---"; grep '^pg_restore: error' "$LOG1" | head -15
  echo "ERROR: pre-data pass failed; target is not safe to continue." >&2
  exit 1
fi

# ------------------------------------------------------------------- pass 2
say "Pass 2/4 - auth users and identities"
AUTHSQL="$LOGDIR/auth_data-$TS.sql"
python3 "$HERE/02_extract_auth.py" --dump "$DUMP" --url "$URL" --out "$AUTHSQL" --pgbin "$PGBIN"

set +e
"$PSQL" "$URL" -v ON_ERROR_STOP=1 -q -f "$AUTHSQL" 2>"$LOGDIR/auth-$TS.log"
RC2=$?
set -e
if [[ "$RC2" -ne 0 ]]; then
  echo "ERROR: auth restore failed:" >&2
  cat "$LOGDIR/auth-$TS.log" >&2
  exit 1
fi
echo "auth.users now: $("$PSQL" "$URL" -tAc 'select count(*) from auth.users')"

# ------------------------------------------------------------------- pass 3
say "Pass 3/4 - data (all rows, no triggers present)"
LOG3="$LOGDIR/data-$TS.log"
set +e
"$PGRESTORE" --no-owner --no-privileges -n public --section=data \
  -d "$URL" "$DUMP" 2>"$LOG3"
RC3=$?
set -e
E3=$(grep -c '^pg_restore: error' "$LOG3" 2>/dev/null || true)
echo "exit=$RC3 errors=$E3  (log: $LOG3)"
if [[ "$E3" -gt 0 ]]; then
  echo "--- first errors ---"; grep '^pg_restore: error' "$LOG3" | head -15
  echo "ERROR: data pass failed. Do NOT continue to post-data." >&2
  exit 1
fi

# ------------------------------------------------------------------- pass 4
# The archive's post-data section includes `ALTER PUBLICATION supabase_realtime
# ADD TABLE public.notifications`. Every Supabase project ships that publication,
# but a bare PostgreSQL cluster does not, so create it first if absent.
"$PSQL" "$URL" -q -c "do \$do\$ begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    execute 'create publication supabase_realtime';
  end if;
end \$do\$;"

say "Pass 4/4 - post-data (indexes, constraints, RLS policies, triggers)"
LOG4="$LOGDIR/post-data-$TS.log"
set +e
"$PGRESTORE" --no-owner --no-privileges -n public --section=post-data \
  -d "$URL" "$DUMP" 2>"$LOG4"
RC4=$?
set -e
E4=$(grep -c '^pg_restore: error' "$LOG4" 2>/dev/null || true)
echo "exit=$RC4 errors=$E4  (log: $LOG4)"
if [[ "$E4" -gt 0 ]]; then
  echo "--- first errors ---"; grep '^pg_restore: error' "$LOG4" | head -15
  echo "ERROR: post-data pass reported errors; review the log before trusting the result." >&2
  exit 1
fi

# --------------------------------------------------- migration history record
# Without this, a later `supabase db push` sees an empty history table and
# tries to re-apply every migration from the beginning.
say "Restoring migration history"
if [[ "$("$PSQL" "$URL" -tAc "select to_regclass('supabase_migrations.schema_migrations') is not null")" == "t" ]]; then
  set +e
  "$PGRESTORE" --no-owner --no-privileges --data-only -n supabase_migrations \
    -d "$URL" "$DUMP" 2>"$LOGDIR/migrations-$TS.log"
  set -e
  echo "schema_migrations rows: $("$PSQL" "$URL" -tAc 'select count(*) from supabase_migrations.schema_migrations')"
else
  echo "WARNING: supabase_migrations.schema_migrations does not exist on the target."
  echo "         Run 'supabase link' once, then re-apply this step." >&2
fi

# ------------------------------------------------------------- post-restore
say "Post-restore: grants, auth trigger, cron jobs, realtime publication"
"$PSQL" "$URL" -v ON_ERROR_STOP=1 -q -f "$HERE/04_post_restore.sql"

say "Done. Now run:  ./05_verify.py --url \"\$TARGET_URL\""
